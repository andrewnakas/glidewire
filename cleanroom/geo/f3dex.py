"""Emit kit meshes in the decomp's own formats: F3DEX Vtx arrays + Gfx display
lists as C source (gbi.h macros) or raw bytes (cleanroom.gfx.gbi packing),
and a generic collision table. Game-specific emitters wrap these.

    batches(tris, cache=32) -> [(vertex ids, local tris)]   vertex-cache batching
    vtx_rows(mesh, ids, tex=32) -> [[x,y,z,flag,s,t,r,g,b,a]]  s16 positions, 10.5 texcoords
    emit_c(name, mesh, cache=32) -> str        Vtx name_vtx[] + Gfx name_dl[]
    emit_bin(mesh, vtx_addr, cache=32) -> (vtx bytes, gfx bytes)
    collision_c(name, mesh) -> str             s16 verts + {surface, a, b, c} triangles
"""
import numpy as np

from cleanroom import binio
from cleanroom.geo.kit import collision
from cleanroom.gfx import gbi


def batches(tris, cache=32):
    out, cur, ids = [], [], {}
    for t in np.asarray(tris).tolist():
        new = [v for v in dict.fromkeys(t) if v not in ids]
        if len(ids) + len(new) > cache:
            out.append((list(ids), cur))
            cur, ids = [], {}
            new = list(dict.fromkeys(t))
        for v in new:
            ids[v] = len(ids)
        cur.append(tuple(ids[v] for v in t))
    if cur:
        out.append((list(ids), cur))
    return out


def _s16(x):
    return int(np.clip(np.round(x), -32768, 32767))


def vtx_rows(mesh, ids, tex=32):
    """Texture coords are shifted per batch by whole repeats (wrap tiles) so
    they stay inside s16."""
    rows = []
    shift = np.floor(mesh.uv[ids].min(axis=0)) if len(ids) else 0
    for v in ids:
        x, y, z = mesh.verts[v]
        s, t = (mesh.uv[v] - shift) * tex * 32     # texels in 10.5 fixed point
        r, g, b, a = (int(c) for c in mesh.color[v])
        rows.append([_s16(x), _s16(y), _s16(z), 0, _s16(s), _s16(t), r, g, b, a])
    return rows


def _tri_cmds(local):
    for k in range(0, len(local) - 1, 2):
        yield ("2", local[k], local[k + 1])
    if len(local) % 2:
        yield ("1", local[-1], None)


def emit_c(name, mesh, cache=32, tex=32):
    vtx, gfx, off = [], [], 0
    for ids, local in batches(mesh.tris, cache):
        for r in vtx_rows(mesh, ids, tex):
            vtx.append("    {{{{ {{{}, {}, {}}}, {}, {{{}, {}}}, {{0x{:02X}, 0x{:02X}, 0x{:02X}, 0x{:02X}}} }}}},".format(*r))
        gfx.append(f"    gsSPVertex({name}_vtx + {off}, {len(ids)}, 0),")
        for kind, a, b in _tri_cmds(local):
            if kind == "2":
                gfx.append(f"    gsSP2Triangles({a[0]}, {a[1]}, {a[2]}, 0, {b[0]}, {b[1]}, {b[2]}, 0),")
            else:
                gfx.append(f"    gsSP1Triangle({a[0]}, {a[1]}, {a[2]}, 0),")
        off += len(ids)
    gfx.append("    gsSPEndDisplayList(),")
    return (f"/* generated by cleanroom.geo.f3dex: {len(mesh.verts)} verts, {len(mesh.tris)} tris */\n"
            f"Vtx {name}_vtx[{off}] = {{\n" + "\n".join(vtx) + "\n};\n\n"
            f"Gfx {name}_dl[] = {{\n" + "\n".join(gfx) + "\n};\n")


def emit_bin(mesh, vtx_addr, cache=32, tex=32):
    vtx, gfx, off = b"", b"", 0
    for ids, local in batches(mesh.tris, cache):
        vtx += binio.build_vtx(vtx_rows(mesh, ids, tex))
        gfx += gbi.sp_vertex(vtx_addr + 16 * off, len(ids), 0)
        for kind, a, b in _tri_cmds(local):
            gfx += gbi.sp_2triangles(a, b) if kind == "2" else gbi.sp_1triangle(*a)
        off += len(ids)
    return vtx, gfx + gbi.sp_end()


def collision_c(name, mesh):
    v, t, s = collision(mesh)
    vs = ",\n".join(f"    {{{_s16(a)}, {_s16(b)}, {_s16(c)}}}" for a, b, c in v)
    ts = ",\n".join(f"    {{{int(k)}, {a}, {b}, {c}}}" for (a, b, c), k in zip(t.tolist(), s))
    return (f"/* generated by cleanroom.geo.f3dex: {len(v)} verts, {len(t)} collision tris */\n"
            f"short {name}_verts[{len(v)}][3] = {{\n{vs}\n}};\n\n"
            f"/* surface type, v0, v1, v2 */\nshort {name}_tris[{len(t)}][4] = {{\n{ts}\n}};\n")
