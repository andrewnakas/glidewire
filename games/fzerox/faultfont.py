ORDER = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ:()-?!+%."


def pixel_flags(n_words=0x40):
    words = [0] * n_words
    for i, ch in enumerate(ORDER):
        base = (i // 5) * 7
        shift = 31 - (i % 5) * 6
        for r, row in enumerate(G[ch]):
            for c, px in enumerate(row):
                if px == "#":
                    words[base + r] |= 1 << (shift - c)
    return words
